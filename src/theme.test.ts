import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { colourRolesCss } from 'household-ui/ui/colourRoles.ts'
import { themeColor } from './theme.ts'

describe('theme.css', () => {
  it('is the household-ui output for themeColor', () => {
    expect(readFileSync('src/theme.css', 'utf8')).toBe(colourRolesCss(themeColor))
  })

  it('is generated by `npm run theme` from the same seed as themeColor', () => {
    const { scripts } = JSON.parse(readFileSync('package.json', 'utf8')) as { scripts: Record<string, string> }
    expect(scripts.theme).toContain(`'${themeColor}'`)
  })
})
